-- 외부 연동(API·콘솔) 목록. 관리자 화면 "외부 연동"에서 보고 고친다(2026-11-20).
-- 키 값은 DB에 두지 않는다. env_keys 에는 환경 변수 이름만 적고, 설정 여부는 서버가 실행 환경에서 확인한다.
CREATE TABLE integrations
(
    integration_id     BIGINT AUTO_INCREMENT PRIMARY KEY,
    code               VARCHAR(40)  NOT NULL,
    name               VARCHAR(60)  NOT NULL,
    provider           VARCHAR(60)  NOT NULL,
    category           VARCHAR(20)  NOT NULL,
    purpose            VARCHAR(300) NOT NULL,
    status             VARCHAR(10)  NOT NULL COMMENT '사용 중 / 준비 중 / 종료',
    icon               VARCHAR(60)  NULL COMMENT '프론트 public/integrations/ 아래 파일 이름',
    site_url           VARCHAR(300) NULL,
    console_url        VARCHAR(300) NULL COMMENT '키 발급·관리 화면',
    docs_url           VARCHAR(300) NULL,
    env_keys           VARCHAR(200) NULL COMMENT '쉼표로 구분한 환경 변수 이름',
    memo               VARCHAR(500) NULL,
    sort_order         INT          NOT NULL DEFAULT 0,
    last_checked_at    DATETIME(6)  NULL,
    last_check_ok      BIT(1)       NULL,
    last_check_message VARCHAR(300) NULL,
    created_at         DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at         DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_integrations_code UNIQUE (code)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

